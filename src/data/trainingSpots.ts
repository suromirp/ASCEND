// ASCEND — places in the Netherlands to train climbing (D+) and descending
// (D−) (production feedback: "waar doe je dat in Nederland überhaupt?").
// From the Trainingsplekken research (docs/onderzoek/notities/Trainingsplekken
// Nederland): coordinates from OpenStreetMap, heights cross-checked with
// Wikipedia's list of Dutch hills. Where sources disagree or a number was
// only found once, `caveat` says so in plain words; nothing is presented
// as more certain than it is. Starting with the Utrecht/Amersfoort region,
// plus the best-known spots elsewhere.

export type SpotUse = 'bergop' | 'bergaf' | 'trap' | 'rugzak' | 'heuvelintervallen' | 'lange tocht' | 'vlak' | 'duurloop';

// One measured climb at a spot. From the Amersfoort/Soest research
// (docs/onderzoek/Trainingsplekken Amersfoort en Soest.md): heights from
// the AHN elevation model (bare ground, ±0,5 m) or Climbfinder; lengths
// measured along a straight line unless the source measured the road.
export interface SpotClimb {
  name: string;
  lengthM: number;
  gainM: number;
  gradePct: number;
  surface: string;
}

// What a catalogue training (data/defaultProgram.ts) looks like at this
// spot, concretely. `limited`: it can be done here, but another spot
// suits it better (the text says which).
export interface SpotSession {
  templateId: string;
  how: string;
  limited?: boolean;
}

export interface TrainingSpot {
  id: string;
  name: string;
  place: string;
  province: string;
  lat: number;
  lon: number;
  // What the coordinate is: a parking/start point, the top, or the middle
  // of the area.
  coordType: 'start' | 'top' | 'gebied';
  kind: string; // "Trap", "Stuwwal", "Duinen", ...
  topM?: number; // highest point, m NAP
  climbM?: number; // height difference of one climb or one stair repeat
  example: string; // what a session there gives
  uses: SpotUse[];
  terrain: string;
  access: string;
  station?: { name: string; km: number }; // straight line
  tip: string;
  caveat?: string;
  region: 'utrecht' | 'elders';
  sources: { label: string; url: string }[];
  // Spots researched in detail say per training how; the others derive
  // their trainings from `uses` (engine/trainingSpots.ts#spotTrainings).
  sessions?: SpotSession[];
  climbs?: SpotClimb[];
  parking?: string;
  lighting?: string;
}

